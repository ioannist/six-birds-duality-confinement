def term_features_mag(H, c, k):
    h = H[(c, k)]
    x = math.log(abs(h))
    if k > 1:
        dx = x - math.log(abs(H[(c, k - 1)]))
    else:
        dx = 0.0
    return [1.0, x, dx, float(k), 1.0 / float(k), x * dx]


def term_features_phase(H, c, k):
    h = H[(c, k)]
    x = math.log(abs(h))
    if k > 1:
        dx = x - math.log(abs(H[(c, k - 1)]))
    else:
        dx = 0.0
    ph = phase(h)
    return [1.0, x, dx, float(k), 1.0 / float(k), math.sin(ph), math.cos(ph)]


def fit_rewrite(H, Z):
    Xmag, ymag, Xphase, yphase = [], [], [], []
    for c in CHARS:
        for k in K_RANGE:
            h = H[(c, k)]
            z = Z[("rho_1", k)]
            Xmag.append(term_features_mag(H, c, k))
            ymag.append(math.log(abs(z)))
            Xphase.append(term_features_phase(H, c, k))
            yphase.append(phase_diff(phase(z), phase(h)))
    Xmag = np.array(Xmag, dtype=float)
    ymag = np.array(ymag, dtype=float)
    Xphase = np.array(Xphase, dtype=float)
    yphase = np.unwrap(np.array(yphase, dtype=float))
    theta, *_ = np.linalg.lstsq(Xmag, ymag, rcond=None)
    eta, *_ = np.linalg.lstsq(Xphase, yphase, rcond=None)

    rows = []
    for i, val in enumerate(theta):
        rows.append({
            "row_type": "parameter", "candidate": "tau_rewrite_term_normalizer",
            "train_target": "rho_1", "test_target": "", "parameter": f"theta_{i}", "value": f"{val:.16g}",
            "lambda_mag": "", "lambda_phase": "", "lambda_operator": "", "lambda_total": "", "admissible": "",
            "note": "magnitude term-normalization coefficient",
        })
    for i, val in enumerate(eta):
        rows.append({
            "row_type": "parameter", "candidate": "tau_rewrite_term_normalizer",
            "train_target": "rho_1", "test_target": "", "parameter": f"eta_{i}", "value": f"{val:.16g}",
            "lambda_mag": "", "lambda_phase": "", "lambda_operator": "", "lambda_total": "", "admissible": "",
            "note": "phase term-normalization coefficient",
        })

    summaries = []
    operator_penalty = 0.30
    for r in RHOS:
        mags, phases, totals = [], [], []
        for c in CHARS:
            for k in K_RANGE:
                h = H[(c, k)]
                z = Z[(r, k)]
                pred_log_abs = float(np.array(term_features_mag(H, c, k)) @ theta)
                pred_phase = phase(h) + float(np.array(term_features_phase(H, c, k)) @ eta)
                lm = abs(pred_log_abs - math.log(abs(z)))
                lp = abs(phase_diff(pred_phase, phase(z)))
                lt = math.sqrt(lm * lm + lp * lp + operator_penalty * operator_penalty)
                mags.append(lm); phases.append(lp); totals.append(lt)
                rows.append({
                    "row_type": "cell", "candidate": "tau_rewrite_term_normalizer",
                    "train_target": "rho_1", "test_target": r, "parameter": "", "value": "",
                    "lambda_mag": f"{lm:.16g}", "lambda_phase": f"{lp:.16g}",
                    "lambda_operator": f"{operator_penalty:.16g}", "lambda_total": f"{lt:.16g}",
                    "admissible": "yes" if lt < 0.05 else "no",
                    "note": f"term=Tau_R[H({c},{k})]; target=Z({r},{k})",
                })
        summaries.append({
            "row_type": "summary", "candidate": "tau_rewrite_term_normalizer",
            "train_target": "rho_1", "test_target": r, "parameter": "ALL", "value": "",
            "lambda_mag": f"{float(np.mean(mags)):.16g}", "lambda_phase": f"{float(np.mean(phases)):.16g}",
            "lambda_operator": f"{operator_penalty:.16g}",
            "lambda_total": f"{float(np.sqrt(np.mean(np.array(totals) ** 2))):.16g}",
            "admissible": "yes" if max(totals) < 0.05 else "no",
            "note": f"mean={np.mean(totals):.6g};median={np.median(totals):.6g};max={np.max(totals):.6g}",
        })

    fields = ["row_type", "candidate", "train_target", "test_target", "parameter", "value", "lambda_mag", "lambda_phase", "lambda_operator", "lambda_total", "admissible", "note"]
    with (OUT / "stage_III_attempt_step365.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows[:13])
        w.writerows(summaries)
        w.writerows(rows[13:])
    return summaries


